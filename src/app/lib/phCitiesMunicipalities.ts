/** Returns the valid city/municipality labels for a selected province. */
export function citiesMunicipalitiesForProvince(province: string): readonly string[] {
  return (PH_CITIES_MUNICIPALITIES_BY_PROVINCE[province.trim()] ?? []).map(
    ([name]) => name,
  );
}

/** Returns local map framing for a valid province/city pair. */
export function cityMunicipalityFocus(
  province: string,
  cityMunicipality: string,
): { center: [number, number]; zoom: number } | null {
  const match = (PH_CITIES_MUNICIPALITIES_BY_PROVINCE[province.trim()] ?? []).find(
    ([name]) => name === cityMunicipality.trim(),
  );
  if (!match) return null;
  const [, latitude, longitude, zoom] = match;
  return { center: [latitude, longitude], zoom };
}
